using System.Collections.Concurrent;
using System.Data;
using System.Globalization;
using System.Reflection;
using Microsoft.Extensions.Options;
using Oracle.ManagedDataAccess.Client;
using SyncEngine.Abstractions.Store;

namespace SyncEngine.Providers.Oracle;

public sealed class OracleOrgStore : IOrgStore
{
    private readonly OracleOptions _options;
    private readonly ConcurrentQueue<Func<CancellationToken, Task>> _postCommitActions = new();
    private OracleConnection? _connection;
    private OracleTransaction? _transaction;
    private bool _disposed;

    public OracleOrgStore(IOptions<OracleOptions> options)
    {
        _options = options.Value;
    }

    public bool HasActiveTransaction => SessionState == OrgStoreSessionState.TransactionOpen;

    public OrgStoreSessionState SessionState
    {
        get
        {
            if (_disposed)
            {
                return OrgStoreSessionState.Disposed;
            }

            if (_transaction is not null)
            {
                return OrgStoreSessionState.TransactionOpen;
            }

            return _connection is { State: ConnectionState.Open }
                ? OrgStoreSessionState.Open
                : OrgStoreSessionState.Idle;
        }
    }

    public async Task EnsureLedgerAsync(CancellationToken cancellationToken = default)
    {
        await EnsureConnectionAsync(cancellationToken);
        await ExecuteAsync(
            """
            DECLARE
                table_count NUMBER;
            BEGIN
                SELECT COUNT(*)
                INTO table_count
                FROM all_tables
                WHERE owner = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
                  AND table_name = 'SYNC_CHANGE';

                IF table_count = 0 THEN
                    EXECUTE IMMEDIATE '
                        CREATE TABLE sync_change (
                            sync_version NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                            entity_name VARCHAR2(128) NOT NULL,
                            operation_name VARCHAR2(20) NOT NULL,
                            entity_key_bytes BLOB NOT NULL,
                            payload_bytes BLOB,
                            changed_at_utc TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                            correlation_id VARCHAR2(64),
                            CONSTRAINT ck_sync_change_operation CHECK (operation_name IN (''UPSERT'', ''DELETE''))
                        )';
                END IF;
            END;
            """,
            cancellationToken: cancellationToken);

        await ExecuteAsync(
            """
            DECLARE
                index_count NUMBER;
            BEGIN
                SELECT COUNT(*)
                INTO index_count
                FROM all_indexes
                WHERE owner = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
                  AND index_name = 'IX_SYNC_CHANGE_ENTITY';

                IF index_count = 0 THEN
                    EXECUTE IMMEDIATE 'CREATE INDEX ix_sync_change_entity ON sync_change(entity_name, sync_version)';
                END IF;
            END;
            """,
            cancellationToken: cancellationToken);
    }

    public async Task<IOrgTransaction> BeginTransactionAsync(CancellationToken cancellationToken = default)
    {
        await EnsureConnectionAsync(cancellationToken);
        if (_transaction is not null)
        {
            throw new InvalidOperationException("A transaction is already active.");
        }

        _transaction = _connection!.BeginTransaction();
        return new OracleOrgTransaction(this);
    }

    public void RegisterPostCommitAction(Func<CancellationToken, Task> action)
    {
        ArgumentNullException.ThrowIfNull(action);
        _postCommitActions.Enqueue(action);
    }

    public async Task<int> ExecuteAsync(
        string sql,
        IReadOnlyDictionary<string, object?>? parameters = null,
        CancellationToken cancellationToken = default)
    {
        await EnsureConnectionAsync(cancellationToken);
        await using var command = CreateCommand(sql, parameters);
        return await command.ExecuteNonQueryAsync(cancellationToken);
    }

    public async Task<IReadOnlyList<T>> QueryAsync<T>(
        string sql,
        IReadOnlyDictionary<string, object?>? parameters = null,
        CancellationToken cancellationToken = default)
        where T : class, new()
    {
        await EnsureConnectionAsync(cancellationToken);
        await using var command = CreateCommand(sql, parameters);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        var results = new List<T>();
        var properties = typeof(T).GetProperties(BindingFlags.Instance | BindingFlags.Public)
            .Where(p => p.CanWrite)
            .ToArray();

        while (await reader.ReadAsync(cancellationToken))
        {
            var item = new T();
            for (var i = 0; i < reader.FieldCount; i++)
            {
                var name = reader.GetName(i);
                var property = properties.FirstOrDefault(p =>
                    string.Equals(p.Name, name, StringComparison.OrdinalIgnoreCase) ||
                    string.Equals(ToPascal(name), p.Name, StringComparison.OrdinalIgnoreCase));
                if (property is null || reader.IsDBNull(i))
                {
                    continue;
                }

                var value = reader.GetValue(i);
                property.SetValue(item, ConvertValue(value, property.PropertyType));
            }

            results.Add(item);
        }

        return results;
    }

    public async Task<T?> QuerySingleOrDefaultAsync<T>(
        string sql,
        IReadOnlyDictionary<string, object?>? parameters = null,
        CancellationToken cancellationToken = default)
        where T : class, new()
    {
        var rows = await QueryAsync<T>(sql, parameters, cancellationToken);
        return rows.FirstOrDefault();
    }

    internal async Task CommitTransactionAsync(CancellationToken cancellationToken)
    {
        if (_transaction is null)
        {
            return;
        }

        await _transaction.CommitAsync(cancellationToken);
        await _transaction.DisposeAsync();
        _transaction = null;

        while (_postCommitActions.TryDequeue(out var action))
        {
            await action(cancellationToken);
        }
    }

    internal async Task RollbackTransactionAsync(CancellationToken cancellationToken)
    {
        while (_postCommitActions.TryDequeue(out _))
        {
        }

        if (_transaction is null)
        {
            return;
        }

        await _transaction.RollbackAsync(cancellationToken);
        await _transaction.DisposeAsync();
        _transaction = null;
    }

    public async ValueTask DisposeAsync()
    {
        if (_disposed)
        {
            return;
        }

        _disposed = true;
        if (_transaction is not null)
        {
            await _transaction.DisposeAsync();
            _transaction = null;
        }

        if (_connection is not null)
        {
            await _connection.DisposeAsync();
            _connection = null;
        }
    }

    private async Task EnsureConnectionAsync(CancellationToken cancellationToken)
    {
        ObjectDisposedException.ThrowIf(_disposed, this);
        if (_connection is { State: ConnectionState.Open })
        {
            return;
        }

        _connection?.Dispose();
        _connection = new OracleConnection(_options.ConnectionString);
        await _connection.OpenAsync(cancellationToken);

        await using var alter = _connection.CreateCommand();
        alter.CommandText = $"ALTER SESSION SET CURRENT_SCHEMA = {_options.Schema}";
        await alter.ExecuteNonQueryAsync(cancellationToken);
    }

    private OracleCommand CreateCommand(string sql, IReadOnlyDictionary<string, object?>? parameters)
    {
        var command = _connection!.CreateCommand();
        command.BindByName = true;
        command.CommandText = sql;
        command.Transaction = _transaction;

        if (parameters is not null)
        {
            foreach (var (key, value) in parameters)
            {
                var name = key.StartsWith(":", StringComparison.Ordinal) ? key : ":" + key;
                var parameter = command.CreateParameter();
                parameter.ParameterName = name;
                parameter.Value = value ?? DBNull.Value;
                if (value is byte[] bytes)
                {
                    parameter.OracleDbType = OracleDbType.Blob;
                    parameter.Value = bytes;
                }

                command.Parameters.Add(parameter);
            }
        }

        return command;
    }

    private static object? ConvertValue(object value, Type targetType)
    {
        var underlying = Nullable.GetUnderlyingType(targetType) ?? targetType;
        if (underlying == typeof(byte[]) && value is byte[] bytes)
        {
            return bytes;
        }

        if (underlying.IsEnum)
        {
            return Enum.ToObject(underlying, value);
        }

        if (underlying == typeof(Guid) && value is string s)
        {
            return Guid.Parse(s);
        }

        if (underlying == typeof(DateTimeOffset))
        {
            if (value is DateTimeOffset dto)
            {
                return dto;
            }

            if (value is DateTime dt)
            {
                return new DateTimeOffset(DateTime.SpecifyKind(dt, DateTimeKind.Utc));
            }
        }

        return Convert.ChangeType(value, underlying, CultureInfo.InvariantCulture);
    }

    private static string ToPascal(string name)
    {
        if (string.IsNullOrWhiteSpace(name))
        {
            return name;
        }

        var parts = name.Split('_', StringSplitOptions.RemoveEmptyEntries);
        return string.Concat(parts.Select(static p =>
            char.ToUpperInvariant(p[0]) + p[1..].ToLowerInvariant()));
    }

    private sealed class OracleOrgTransaction(OracleOrgStore store) : IOrgTransaction
    {
        public Task CommitAsync(CancellationToken cancellationToken = default)
            => store.CommitTransactionAsync(cancellationToken);

        public Task RollbackAsync(CancellationToken cancellationToken = default)
            => store.RollbackTransactionAsync(cancellationToken);

        public ValueTask DisposeAsync() => ValueTask.CompletedTask;
    }
}
