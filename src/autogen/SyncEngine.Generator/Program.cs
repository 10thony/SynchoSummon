using System.Text;
using System.Text.Json;
using Microsoft.Extensions.DependencyInjection;
using SyncEngine.Abstractions.Schema;
using SyncEngine.Providers.Oracle;

var connection = GetArg(args, "--connection")
    ?? Environment.GetEnvironmentVariable("SYNCENGINE_ORACLE")
    ?? "User Id=nas_sim;Password=NasSim_Dev1;Data Source=localhost:1522/FREEPDB1";
var schema = GetArg(args, "--schema") ?? "NAS_SIM";
var output = GetArg(args, "--out") ?? "./generated";
var dryRun = args.Contains("--dry-run", StringComparer.OrdinalIgnoreCase);
var help = args.Contains("--help", StringComparer.OrdinalIgnoreCase) || args.Contains("-h", StringComparer.OrdinalIgnoreCase);

if (help)
{
    Console.WriteLine(
        """
        SyncEngine schema generator (Oracle-first)

          --connection <cs>   Oracle connection string
          --schema <name>     Schema owner (default NAS_SIM)
          --out <dir>         Output directory (default ./generated)
          --dry-run           List entities only
          --help              Show help
        """);
    return 0;
}

var services = new ServiceCollection();
services.AddSyncEngineOracle(o =>
{
    o.ConnectionString = connection;
    o.Schema = schema;
});
await using var provider = services.BuildServiceProvider();
var reader = provider.GetRequiredService<ISchemaReader>();

Console.WriteLine($"Reading schema '{schema}'...");
IReadOnlyList<EntityDescriptor> entities;
try
{
    entities = await reader.ReadEntitiesAsync();
}
catch (Exception ex)
{
    Console.Error.WriteLine($"Schema read failed: {ex.Message}");
    Console.Error.WriteLine("Generator scaffold is ready; start infra Oracle to emit entities.");
    return 1;
}

Console.WriteLine($"Discovered {entities.Count} entities.");
if (dryRun)
{
    foreach (var entity in entities)
    {
        Console.WriteLine($"- {entity.EntityName} ({entity.TableName}) keys=[{string.Join(',', entity.KeyColumns)}]");
    }

    return 0;
}

Directory.CreateDirectory(output);
var manifestPath = Path.Combine(output, "manifest.json");
await File.WriteAllTextAsync(
    manifestPath,
    JsonSerializer.Serialize(entities.Select(e => new
    {
        e.EntityName,
        e.TableName,
        e.KeyColumns,
        e.Syncable,
        Properties = e.Properties.Select(p => new { p.PropertyName, p.ColumnName, Type = p.ClrType.Name, p.IsKey }),
    }), new JsonSerializerOptions { WriteIndented = true }));

foreach (var entity in entities.Where(e => e.Syncable))
{
    var sb = new StringBuilder();
    sb.AppendLine("// <auto-generated />");
    sb.AppendLine("using MemoryPack;");
    sb.AppendLine();
    sb.AppendLine("namespace SyncEngine.Generated;");
    sb.AppendLine();
    sb.AppendLine("[MemoryPackable]");
    sb.AppendLine($"public partial class {entity.EntityName}");
    sb.AppendLine("{");
    foreach (var property in entity.Properties)
    {
        var typeName = property.ClrType == typeof(string)
            ? "string"
            : property.ClrType == typeof(byte[])
                ? "byte[]"
                : property.ClrType.Name;
        var suffix = property.ClrType == typeof(string) ? " = string.Empty;" : ";";
        sb.AppendLine($"    public {typeName} {property.PropertyName} {{ get; set; }}{suffix}");
    }

    sb.AppendLine("}");
    await File.WriteAllTextAsync(Path.Combine(output, $"{entity.EntityName}.cs"), sb.ToString());
}

Console.WriteLine($"Wrote manifest + {entities.Count(e => e.Syncable)} model stubs to {Path.GetFullPath(output)}");
return 0;

static string? GetArg(string[] args, string name)
{
    for (var i = 0; i < args.Length - 1; i++)
    {
        if (string.Equals(args[i], name, StringComparison.OrdinalIgnoreCase))
        {
            return args[i + 1];
        }
    }

    return null;
}
