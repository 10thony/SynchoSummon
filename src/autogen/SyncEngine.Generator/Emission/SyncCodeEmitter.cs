    private async Task WriteProjectFileAsync(CancellationToken ct)
    {
        // Relative refs assume generated folder lives under repo samples/generated or similar.
        // Hosts can also compile sources via Compile Include; project file is a convenience.
        var csproj =
            $"""
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <ImplicitUsings>enable</ImplicitUsings>
                <Nullable>enable</Nullable>
                <RootNamespace>{RootNamespace}</RootNamespace>
                <SyncEngineSrcRoot Condition="'$(SyncEngineSrcRoot)' == ''">..\..\..\src\core\</SyncEngineSrcRoot>
              </PropertyGroup>
              <ItemGroup>
                <PackageReference Include="MemoryPack" Version="1.21.4" />
                <FrameworkReference Include="Microsoft.AspNetCore.App" />
              </ItemGroup>
              <ItemGroup>
                <ProjectReference Include="$(SyncEngineSrcRoot)SyncEngine.Abstractions\SyncEngine.Abstractions.csproj" />
                <ProjectReference Include="$(SyncEngineSrcRoot)SyncEngine.Server\SyncEngine.Server.csproj" />
                <ProjectReference Include="$(SyncEngineSrcRoot)SyncEngine.Client\SyncEngine.Client.csproj" />
                <ProjectReference Include="$(SyncEngineSrcRoot)SyncEngine.Client.Sqlite\SyncEngine.Client.Sqlite.csproj" />
              </ItemGroup>
            </Project>
            """;

        await File.WriteAllTextAsync(Path.Combine(OutputRoot, $"{RootNamespace}.csproj"), csproj, ct);
    }

    private static string Camel(string name)
        => string.IsNullOrEmpty(name) ? name : char.ToLowerInvariant(name[0]) + name[1..];

    private static string ToKebab(string name)
    {
        var sb = new StringBuilder();
        for (var i = 0; i < name.Length; i++)
        {
            var ch = name[i];
            if (char.IsUpper(ch) && i > 0)
            {
                sb.Append('-');
            }

            sb.Append(char.ToLowerInvariant(ch));
        }

        return Pluralize(sb.ToString());
    }

    private static string Pluralize(string singular)
    {
        if (singular.EndsWith("y", StringComparison.Ordinal)
            && singular.Length > 1
            && !"aeiou".Contains(singular[^2]))
        {
            return singular[..^1] + "ies";
        }

        if (singular.EndsWith("s", StringComparison.Ordinal)
            || singular.EndsWith("x", StringComparison.Ordinal)
            || singular.EndsWith("z", StringComparison.Ordinal)
            || singular.EndsWith("ch", StringComparison.Ordinal)
            || singular.EndsWith("sh", StringComparison.Ordinal))
        {
            return singular + "es";
        }

        return singular + "s";
    }

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
