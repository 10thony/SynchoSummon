using System.Text;
using System.Text.Json;
using SyncEngine.Abstractions.Schema;

namespace SyncEngine.Generator.Emission;

/// <summary>
/// Deterministic, non-LLM emitter: schema IR → compilable SyncEngine plug-in sources.
/// </summary>
public sealed class SyncCodeEmitter
{
    public required string RootNamespace { get; init; } = "SyncEngine.Generated";

    public required string OutputRoot { get; init; }

    public async Task EmitAsync(IReadOnlyList<EntityDescriptor> entities, CancellationToken cancellationToken = default)
    {
        var syncable = entities.Where(e => e.Syncable).ToList();
        Directory.CreateDirectory(OutputRoot);
        Directory.CreateDirectory(Path.Combine(OutputRoot, "Models"));
        Directory.CreateDirectory(Path.Combine(OutputRoot, "Server"));
        Directory.CreateDirectory(Path.Combine(OutputRoot, "Client"));

        await WriteManifestAsync(syncable, cancellationToken);
        await WriteEntityNamesAsync(syncable, cancellationToken);
        foreach (var entity in syncable)
        {
            await WriteModelAsync(entity, cancellationToken);
        }

        await WriteServerStoreAsync(syncable, cancellationToken);
        await WriteOfflineApplicatorAsync(syncable, cancellationToken);
        await WriteRestEndpointsAsync(syncable, cancellationToken);
        await WriteServerDiAsync(syncable, cancellationToken);
        await WriteClientDiAsync(syncable, cancellationToken);
        await WriteProjectFileAsync(cancellationToken);
    }

    private async Task WriteManifestAsync(IReadOnlyList<EntityDescriptor> entities, CancellationToken ct)
    {
        var payload = entities.Select(e => new
        {
            e.EntityName,
            e.TableName,
            e.SchemaName,
            e.KeyColumns,
            e.Syncable,
            e.DependencyOrder,
            e.ReferencedTables,
            Properties = e.Properties.Select(p => new
            {
                p.PropertyName,
                p.ColumnName,
                Type = CSharpNames.TypeName(p.ClrType),
                p.IsKey,
                p.IsPayload,
                p.IsNullable,
            }),
        });

        var path = Path.Combine(OutputRoot, "manifest.json");
        await File.WriteAllTextAsync(
            path,
            JsonSerializer.Serialize(payload, new JsonSerializerOptions { WriteIndented = true }),
            ct);
    }

    private async Task WriteEntityNamesAsync(IReadOnlyList<EntityDescriptor> entities, CancellationToken ct)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine($"namespace {RootNamespace};");
        sb.AppendLine();
        sb.AppendLine("public static class EntityNames");
        sb.AppendLine("{");
        foreach (var entity in entities)
        {
            var id = CSharpNames.SanitizeIdentifier(entity.EntityName);
            sb.AppendLine($"    public const string {id} = \"{Escape(entity.EntityName)}\";");
        }

        sb.AppendLine();
        sb.AppendLine("    public static readonly string[] All =");
        sb.AppendLine("    [");
        foreach (var entity in entities)
        {
            sb.AppendLine($"        {CSharpNames.SanitizeIdentifier(entity.EntityName)},");
        }

        sb.AppendLine("    ];");
        sb.AppendLine("}");
        await File.WriteAllTextAsync(Path.Combine(OutputRoot, "EntityNames.cs"), sb.ToString(), ct);
    }

    private async Task WriteModelAsync(EntityDescriptor entity, CancellationToken ct)
    {
        var name = CSharpNames.SanitizeIdentifier(entity.EntityName);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("using MemoryPack;");
        sb.AppendLine();
        sb.AppendLine($"namespace {RootNamespace}.Models;");
        sb.AppendLine();
        sb.AppendLine("[MemoryPackable]");
        sb.AppendLine($"public partial class {name}");
        sb.AppendLine("{");
        foreach (var property in entity.Properties)
        {
            var propName = CSharpNames.SanitizeIdentifier(property.PropertyName);
            var typeName = CSharpNames.PropertyType(property.ClrType, property.IsNullable);
            var suffix = CSharpNames.DefaultSuffix(property.ClrType, property.IsNullable);
            sb.AppendLine($"    public {typeName} {propName} {{ get; set; }}{suffix}");
        }

        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("[MemoryPackable]");
        sb.AppendLine($"public partial class {name}Key");
        sb.AppendLine("{");
        var keyProps = entity.Properties.Where(p => p.IsKey).ToList();
        if (keyProps.Count == 0)
        {
            sb.AppendLine("    public string Id { get; set; } = string.Empty;");
        }
        else
        {
            foreach (var property in keyProps)
            {
                var propName = CSharpNames.SanitizeIdentifier(property.PropertyName);
                var typeName = CSharpNames.PropertyType(property.ClrType, nullable: false);
                var suffix = CSharpNames.DefaultSuffix(property.ClrType, nullable: false);
                sb.AppendLine($"    public {typeName} {propName} {{ get; set; }}{suffix}");
            }
        }

        sb.AppendLine("}");

        await File.WriteAllTextAsync(Path.Combine(OutputRoot, "Models", $"{name}.cs"), sb.ToString(), ct);
    }

    private async Task WriteServerStoreAsync(IReadOnlyList<EntityDescriptor> entities, CancellationToken ct)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("using System.Collections.Concurrent;");
        sb.AppendLine($"using {RootNamespace};");
        sb.AppendLine($"using {RootNamespace}.Models;");
        sb.AppendLine("using SyncEngine.Abstractions.Codec;");
        sb.AppendLine("using SyncEngine.Abstractions.Ledger;");
        sb.AppendLine();
        sb.AppendLine($"namespace {RootNamespace}.Server;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>In-memory org projection + ledger writer hooks for generated entities.</summary>");
        sb.AppendLine("public sealed class GeneratedEntityStore(IChangeLedgerWriter ledgerWriter, IDeltaCodec codec)");
        sb.AppendLine("{");

        foreach (var entity in entities)
        {
            var name = CSharpNames.SanitizeIdentifier(entity.EntityName);
            sb.AppendLine($"    private readonly ConcurrentDictionary<string, {name}> _{Camel(name)} = new(StringComparer.Ordinal);");
        }

        sb.AppendLine();

        foreach (var entity in entities)
        {
            var name = CSharpNames.SanitizeIdentifier(entity.EntityName);
            var keyProp = entity.Properties.FirstOrDefault(p => p.IsKey)?.PropertyName ?? "Id";
            var keyId = CSharpNames.SanitizeIdentifier(keyProp);

            sb.AppendLine($"    public IEnumerable<{name}> List{name}() => _{Camel(name)}.Values.OrderBy(x => x.{keyId}.ToString());");
            sb.AppendLine();
            sb.AppendLine($"    public void Put{name}({name} entity) => _{Camel(name)}[entity.{keyId}.ToString()!] = entity;");
            sb.AppendLine();
            sb.AppendLine($"    public async Task<{name}> Upsert{name}Async({name} entity, CancellationToken cancellationToken = default)");
            sb.AppendLine("    {");
            sb.AppendLine($"        Put{name}(entity);");
            sb.AppendLine($"        using var key = codec.Encode(new {name}Key {{ {keyId} = entity.{keyId} }});");
            sb.AppendLine("        using var payload = codec.Encode(entity);");
            sb.AppendLine($"        await ledgerWriter.RecordUpsertAsync(EntityNames.{name}, key.Memory, payload.Memory, cancellationToken: cancellationToken);");
            sb.AppendLine("        return entity;");
            sb.AppendLine("    }");
            sb.AppendLine();
            var keyClr = entity.Properties.FirstOrDefault(p => p.IsKey)?.ClrType ?? typeof(string);
            var keyTypeName = CSharpNames.TypeName(keyClr);
            sb.AppendLine($"    public async Task Delete{name}Async(string key, CancellationToken cancellationToken = default)");
            sb.AppendLine("    {");
            sb.AppendLine($"        _{Camel(name)}.TryRemove(key, out _);");
            sb.AppendLine($"        var typedKey = new {name}Key {{ {keyId} = ParseKey<{keyTypeName}>(key) }};");
            sb.AppendLine("        using var keyBytes = codec.Encode(typedKey);");
            sb.AppendLine($"        await ledgerWriter.RecordDeleteAsync(EntityNames.{name}, keyBytes.Memory, cancellationToken: cancellationToken);");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("    private static T ParseKey<T>(string key)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (typeof(T) == typeof(string)) return (T)(object)key;");
        sb.AppendLine("        if (typeof(T) == typeof(Guid)) return (T)(object)Guid.Parse(key);");
        sb.AppendLine("        if (typeof(T) == typeof(int)) return (T)(object)int.Parse(key);");
        sb.AppendLine("        if (typeof(T) == typeof(long)) return (T)(object)long.Parse(key);");
        sb.AppendLine("        if (typeof(T) == typeof(decimal)) return (T)(object)decimal.Parse(key);");
        sb.AppendLine("        return (T)Convert.ChangeType(key, typeof(T));");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        await File.WriteAllTextAsync(Path.Combine(OutputRoot, "Server", "GeneratedEntityStore.cs"), sb.ToString(), ct);
    }

    private async Task WriteOfflineApplicatorAsync(IReadOnlyList<EntityDescriptor> entities, CancellationToken ct)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine($"using {RootNamespace};");
        sb.AppendLine($"using {RootNamespace}.Models;");
        sb.AppendLine("using SyncEngine.Abstractions.Codec;");
        sb.AppendLine("using SyncEngine.Abstractions.Protocol;");
        sb.AppendLine("using SyncEngine.Abstractions.Offline;");
        sb.AppendLine();
        sb.AppendLine($"namespace {RootNamespace}.Server;");
        sb.AppendLine();
        sb.AppendLine("public sealed class GeneratedOfflineApplicator(GeneratedEntityStore store, IDeltaCodec codec) : IOfflineEntityApplicator");
        sb.AppendLine("{");
        sb.AppendLine("    public Task ApplyFromClientAsync(DeltaChange change, CancellationToken cancellationToken = default)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (change.Operation != DeltaOperation.Upsert || change.PayloadBytes is not { Length: > 0 } payload)");
        sb.AppendLine("        {");
        sb.AppendLine("            return Task.CompletedTask;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        switch (change.EntityName)");
        sb.AppendLine("        {");
        foreach (var entity in entities)
        {
            var name = CSharpNames.SanitizeIdentifier(entity.EntityName);
            sb.AppendLine($"            case EntityNames.{name}:");
            sb.AppendLine($"                store.Put{name}(codec.Decode<{name}>(payload));");
            sb.AppendLine("                break;");
        }

        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return Task.CompletedTask;");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        await File.WriteAllTextAsync(Path.Combine(OutputRoot, "Server", "GeneratedOfflineApplicator.cs"), sb.ToString(), ct);
    }

    private async Task WriteRestEndpointsAsync(IReadOnlyList<EntityDescriptor> entities, CancellationToken ct)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine($"using {RootNamespace}.Models;");
        sb.AppendLine("using Microsoft.AspNetCore.Builder;");
        sb.AppendLine("using Microsoft.AspNetCore.Http;");
        sb.AppendLine("using Microsoft.AspNetCore.Routing;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine("using SyncEngine.Abstractions.Auth;");
        sb.AppendLine();
        sb.AppendLine($"namespace {RootNamespace}.Server;");
        sb.AppendLine();
        sb.AppendLine("public static class GeneratedRestEndpoints");
        sb.AppendLine("{");
        sb.AppendLine("    public static IEndpointRouteBuilder MapGeneratedSyncRest(this IEndpointRouteBuilder endpoints)");
        sb.AppendLine("    {");
        sb.AppendLine("        var requireAuth = endpoints.ServiceProvider");
        sb.AppendLine("            .GetService<SyncEngine.Server.Hosting.SyncAuthFeature>()");
        sb.AppendLine("            ?.RequireAuthenticatedClients == true;");
        sb.AppendLine();
        sb.AppendLine("        RouteHandlerBuilder Secure(RouteHandlerBuilder builder)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (requireAuth)");
        sb.AppendLine("            {");
        sb.AppendLine("                builder.RequireAuthorization(SyncAuthPolicies.SyncClient);");
        sb.AppendLine("            }");
        sb.AppendLine("            return builder;");
        sb.AppendLine("        }");
        sb.AppendLine();

        foreach (var entity in entities)
        {
            var name = CSharpNames.SanitizeIdentifier(entity.EntityName);
            var route = ToKebab(entity.EntityName);
            sb.AppendLine($"        Secure(endpoints.MapGet(\"/api/{route}\", (GeneratedEntityStore store) => Results.Ok(store.List{name}())));");
            sb.AppendLine($"        Secure(endpoints.MapPost(\"/api/{route}\", async ({name} entity, GeneratedEntityStore store, CancellationToken ct) =>");
            sb.AppendLine($"            Results.Ok(await store.Upsert{name}Async(entity, ct))));");
            sb.AppendLine($"        Secure(endpoints.MapDelete(\"/api/{route}/{{key}}\", async (string key, GeneratedEntityStore store, CancellationToken ct) =>");
            sb.AppendLine("        {");
            sb.AppendLine($"            await store.Delete{name}Async(key, ct);");
            sb.AppendLine("            return Results.NoContent();");
            sb.AppendLine("        }));");
            sb.AppendLine();
        }

        sb.AppendLine("        return endpoints;");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        await File.WriteAllTextAsync(Path.Combine(OutputRoot, "Server", "GeneratedRestEndpoints.cs"), sb.ToString(), ct);
    }

